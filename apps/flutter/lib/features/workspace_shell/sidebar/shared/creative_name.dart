import 'dart:math' as math;

/// `generateCreativeWorkflowName` (`stores/workflows/registry/utils.ts:1-216`):
/// a lowercase `machine-nature` name whose letters total one of
/// [preferredNameLengths], weighted toward seven.
String generateCreativeWorkflowName([math.Random? random]) {
  final rng = random ?? math.Random.secure();
  final length = preferredNameLengths[rng.nextInt(preferredNameLengths.length)];
  final names = workflowNamesByLength[length]!;
  return names[rng.nextInt(names.length)];
}

const List<int> preferredNameLengths = <int>[
  7,
  7,
  7,
  7,
  7,
  6,
  6,
  6,
  6,
  8,
  8,
  8,
  9,
  9,
  10,
];

/// `WORKFLOW_NAMES_BY_LENGTH`: every machine x nature pair keyed by its
/// letter count (6..10).
final Map<int, List<String>> workflowNamesByLength = () {
  final byLength = <int, List<String>>{
    for (var i = 6; i <= 10; i++) i: <String>[],
  };
  for (final machine in _machineWords) {
    for (final nature in _natureWords) {
      final length = machine.length + nature.length;
      final bucket = byLength[length];
      if (bucket == null) {
        throw RangeError(
          'Workflow name words must total 6-10 letters, received $length',
        );
      }
      bucket.add('$machine-$nature');
    }
  }
  return byLength;
}();

