/// Copies the emcn icon set into this package and writes
/// `lib/src/icons/sim_emcn_icons.g.dart`.
///
/// Inputs come from the extraction step (`tools/gen`), which renders every
/// `packages/emcn/src/icons/*.tsx` export to `generated/icons/emcn/*.svg` and
/// precompiles it to `generated/icons_vec/emcn/*.vec`; `generated/icons/
/// report.json` maps each file to its export name.
///
/// Icons that already ship hand-ported in `assets/icons/` (the `SimIcons`
/// set) are aliased to those constants instead of being copied twice.
///
///   dart run tool/generate_emcn_icons.dart `[generatedRoot]`
///
/// `generatedRoot` defaults to `../../generated` (the app's `generated/`).
library;

import 'dart:convert';
import 'dart:io';

const String _assetDir = 'assets/icons/emcn';
const String _handPortedDir = 'assets/icons';
const String _handPortedDart = 'lib/src/icons/sim_icons.dart';
const String _output = 'lib/src/icons/sim_emcn_icons.g.dart';

Future<void> main(List<String> args) async {
  final generated = Directory(args.isEmpty ? '../../generated' : args.first);
  final reportFile = File('${generated.path}/icons/report.json');
  if (!reportFile.existsSync()) {
    stderr.writeln('missing ${reportFile.path}; run tools/gen first');
    exitCode = 2;
    return;
  }
  final report = jsonDecode(reportFile.readAsStringSync()) as Map;
  final icons = (report['icons']! as Map).cast<String, Object?>();
  final handPorted = _handPortedConstants();

  final target = Directory(_assetDir);
  if (target.existsSync()) target.deleteSync(recursive: true);
  target.createSync(recursive: true);

  final entries = <_Icon>[];
  final missing = <String>[];
  for (final MapEntry(:key, :value) in icons.entries) {
    if (!key.startsWith('emcn/')) continue;
    final stem = key.substring('emcn/'.length);
    final export = (value! as Map)['export']! as String;
    final alias = handPorted[stem];
    if (alias != null) {
      entries.add(_Icon(export: export, stem: stem, alias: alias));
      continue;
    }
    final svg = File('${generated.path}/icons/emcn/$stem.svg');
    final vec = File('${generated.path}/icons_vec/emcn/$stem.vec');
    if (!svg.existsSync()) {
      missing.add('$stem.svg');
      continue;
    }
    svg.copySync('$_assetDir/$stem.svg');
    final precompiled = vec.existsSync();
    if (precompiled) {
      vec.copySync('$_assetDir/$stem.vec');
    } else {
      missing.add('$stem.vec (SVG fallback)');
    }
    entries.add(_Icon(export: export, stem: stem, precompiled: precompiled));
  }
  entries.sort((a, b) => a.name.compareTo(b.name));

  final names = <String>{};
  for (final e in entries) {
    if (!names.add(e.name)) {
      stderr.writeln('duplicate constant ${e.name}');
      exitCode = 1;
      return;
    }
  }

  File(_output).writeAsStringSync(_render(entries));
  final format = await Process.run('dart', <String>[
    'format',
    _output,
  ], runInShell: true);
  if (format.exitCode != 0) stderr.write(format.stderr);

  stdout.writeln(
    'emcn icons: ${entries.length} constants, '
    '${entries.where((e) => e.alias == null).length} copied, '
    '${entries.where((e) => e.alias != null).length} aliased to SimIcons',
  );
  if (missing.isNotEmpty) stdout.writeln('missing: ${missing.join(', ')}');
}

/// `SimIcons` constants keyed by their asset stem, read from the source so
/// the generator never drifts from the hand-ported set.
Map<String, String> _handPortedConstants() {
  final source = File(_handPortedDart).readAsStringSync();
  final pattern = RegExp(
    r"static const SimIconData (\w+) = SimIconData\('([\w-]+)'\);",
  );
  return <String, String>{
    for (final m in pattern.allMatches(source))
      if (File('$_handPortedDir/${m.group(2)}.svg').existsSync())
        m.group(2)!: m.group(1)!,
  };
}

String _render(List<_Icon> entries) {
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/generate_emcn_icons.dart. Do not edit.')
    ..writeln('// Source: generated/icons/emcn (packages/emcn/src/icons).')
    ..writeln()
    ..writeln("import 'package:sim_design/src/icons/sim_icons.dart';")
    ..writeln()
    ..writeln(
      '/// Every `@sim/emcn/icons` export, named after the export '
      '(`Workflow` -> [SimEmcnIcons.workflow]).',
    )
    ..writeln('///')
    ..writeln(
      '/// Precompiled `.vec` assets tinted through a `srcIn` colour filter; '
      'icons that',
    )
    ..writeln(
      '/// overlap the hand-ported [SimIcons] set alias those constants.',
    )
    ..writeln('abstract final class SimEmcnIcons {');
  for (final e in entries) {
    if (e.alias != null) {
      b.writeln('  static const SimIconData ${e.name} = SimIcons.${e.alias};');
    } else {
      final flag = e.precompiled ? ', precompiled: true' : '';
      b.writeln(
        "  static const SimIconData ${e.name} = SimIconData('emcn/${e.stem}'$flag);",
      );
    }
  }
  b
    ..writeln()
    ..writeln('  /// Export name (`ArrowDown`) to icon.')
    ..writeln('  static const Map<String, SimIconData> byExport =')
    ..writeln('      <String, SimIconData>{');
  for (final e in entries) {
    b.writeln("    '${e.export}': ${e.name},");
  }
  b
    ..writeln('  };')
    ..writeln()
    ..writeln('  static const List<SimIconData> all = <SimIconData>[');
  for (final e in entries) {
    b.writeln('    ${e.name},');
  }
  b
    ..writeln('  ];')
    ..writeln('}');
  return b.toString();
}

class _Icon {
  _Icon({
    required this.export,
    required this.stem,
    this.alias,
    this.precompiled = false,
  });

  final String export;
  final String stem;
  final String? alias;
  final bool precompiled;

  String get name => export[0].toLowerCase() + export.substring(1);
}
